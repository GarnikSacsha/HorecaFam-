from dataclasses import dataclass


@dataclass(frozen=True)
class CatalogLesson:
    title: str
    text: str


@dataclass(frozen=True)
class CatalogScenario:
    lesson: int
    scenario: str
    action: str
    alternatives: tuple[str, str]
    explanation: str


@dataclass(frozen=True)
class CatalogCourse:
    code: str
    title: str
    positions: tuple[str, ...]
    lessons: tuple[CatalogLesson, ...]
    scenarios: tuple[CatalogScenario, ...]


